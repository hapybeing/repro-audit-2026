# ---------- B cross-check ----------
def rows(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))

B = os.path.join(P, "B")
bmain = {r["model"]: r for r in rows(os.path.join(B, "outputs", "main_all_terms.csv")) if r["term"] == "SDO_index"}
brc = {r["model"]: r for r in rows(os.path.join(B, "outputs", "Rc_all_terms.csv")) if r["term"] == "SDO_index"}
bfacts = rows(os.path.join(B, "outputs", "diag_sdo_facts.csv"))[0]
bcols = [r["selected_columns"] for r in rows(os.path.join(B, "outputs", "diag_sdo_selected_columns.csv"))]
review = open(os.path.join(B, "outputs", "code_review.md"), encoding="utf-8").read()
bres = json.load(open(os.path.join(B, "results.json")))
bbugs = bres.get("bugs", [])
sc = d["sdo_coefficient"]
amap = {("model_CTB", "a"): sc["Table_A1_logistic_CT"]["a_original"], ("model_misinfo", "a"): sc["Table_A2_logistic_misinfo"]["a_original"],
        ("model_CTB", "b"): sc["Table_A1_logistic_CT"]["b_corrected_Rc"], ("model_misinfo", "b"): sc["Table_A2_logistic_misinfo"]["b_corrected_Rc"]}
cmp = []
for (m, v), a in amap.items():
    b = (bmain if v == "a" else brc)[m]
    cmp.append({"model": m, "version": "a_original" if v == "a" else "b_corrected_Rc",
                "B_odds_ratio": float(b["odds_ratio"]), "A_odds_ratio": a["odds_ratio"],
                "abs_diff_odds_ratio": abs(float(b["odds_ratio"]) - a["odds_ratio"]),
                "B_p_raw": float(b["p_raw"]), "B_p_bonf": float(b["p_bonf"]),
                "abs_diff_p_raw": abs(float(b["p_raw"]) - a["p_raw"])})
heading = [l.strip() for l in review.splitlines() if l.startswith("## ") and "SDO" in l]
d["B_cross_check"] = {
    "source_files": ["B/outputs/code_review.md", "B/results.json", "B/outputs/main_all_terms.csv", "B/outputs/Rc_all_terms.csv",
                     "B/outputs/diag_sdo_facts.csv", "B/outputs/diag_sdo_selected_columns.csv"],
    "B_code_review_flags_sdo_line_1035": bool(re.search(r"SDO index.*line 1035", review)),
    "B_code_review_heading": heading[0] if heading else None,
    "B_results_json_lists_bug_at_line_1035": any(b.get("line") == 1035 for b in bbugs),
    "B_results_json_lists_bug_at_line_1770": any(b.get("line") == 1770 for b in bbugs),
    "B_selected_columns": bcols,
    "B_n_complete": int(bfacts["n_complete_sdo"]),
    "B_max_abs_diff_vs_4_plus_SDO2_SDO4_over_6": float(bfacts["max_abs_diff_orig_vs_4_plus_SDO2_SDO4_over_6_complete"]),
    "B_cor_orig_vs_4item_complete": float(bfacts["cor_orig_vs_4item_complete"]),
    "B_alpha_4item": float(bfacts["alpha_4item_as_line982"]),
    "sdo_coefficient_A_vs_B": cmp,
    "max_abs_diff_odds_ratio_A_vs_B": max(c["abs_diff_odds_ratio"] for c in cmp),
    "B_mentions_duplicate_ids": bool(re.search(r"duplicat", review, re.I)),
}
json.dump(d, open(JS, "w"), indent=1)

