"""Clock comparison for 02_ELBOXX (reviewer point 2).

Reads the two saved Path A outputs (authors' replication.R unchanged):
  - outputs/targets_pathA_faketime20250506.csv  (process clock set to the authors' run date 2025-05-06)
  - outputs/targets_pathA_clock2026.csv         (real clock, 2026-10-09)
plus their meta_*.csv files and targets.json, and writes outputs/clock_comparison.json with, per target:
paper value, value with authors' run date, value as-is, relative diffs vs the paper and between runs.
No R re-run is needed: both runs are already saved. Usage: python3 clock_comparison.py (from any dir).
"""
import csv, json, os, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
A = os.path.dirname(HERE)
PAPER = os.path.dirname(A)
OUT = os.path.join(A, "outputs")

FAKE = "targets_pathA_faketime20250506.csv"
REAL = "targets_pathA_clock2026.csv"
MAP = {  # target id -> (test row, column)
    "T1": ("M2_test2_pubdef1", "r"),
    "T2": ("M2_test2_pubdef1", "ci_low"),
    "T3": ("M2_test2_pubdef1", "ci_high"),
    "T4": ("M1_test1_all", "r"),
    "T5": ("M1_test1_all", "ci_low"),
}

def rows(fn):
    with open(os.path.join(OUT, fn)) as f:
        return {r["test"]: r for r in csv.DictReader(f)}

def meta(fn):
    with open(os.path.join(OUT, fn)) as f:
        return next(csv.DictReader(f))

fake, real = rows(FAKE), rows(REAL)
mfake, mreal = meta("meta_pathA_faketime20250506.csv"), meta("meta_pathA_clock2026.csv")
targets = json.load(open(os.path.join(PAPER, "targets.json")))

out_targets = []
for t in targets:
    test, col = MAP[t["id"]]
    pv = float(t["paper_value"]); dec = int(t["paper_rounding_decimals"])
    vf, vr = float(fake[test][col]), float(real[test][col])
    out_targets.append({
        "id": t["id"], "test": test, "statistic": col,
        "paper_value": pv, "paper_rounding_decimals": dec,
        "value_authors_run_date_20250506": vf,
        "value_as_is_clock_20261009": vr,
        "rel_diff_authors_date_vs_paper": (vf - pv) / pv,
        "rel_diff_as_is_vs_paper": (vr - pv) / pv,
        "rel_diff_as_is_vs_authors_date": (vr - vf) / vf,
        "match_to_rounding_authors_date": round(vf, dec) == round(pv, dec),
        "match_to_rounding_as_is": round(vr, dec) == round(pv, dec),
        "within_5pct_as_is": abs((vr - pv) / pv) <= 0.05,
        "n_authors_date": int(fake[test]["n"]), "n_as_is": int(real[test]["n"]),
        "p_authors_date": float(fake[test]["p"]), "p_as_is": float(real[test]["p"]),
    })

res = {
    "paper_id": "02_ELBOXX",
    "description": "Path A (authors' replication.R unchanged) run twice: process clock set to the authors' run date vs real clock.",
    "generated_by": "papers/02_ELBOXX/A/scripts/clock_comparison.py",
    "generated_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
    "sources": {"authors_run_date": ["outputs/" + FAKE, "outputs/meta_pathA_faketime20250506.csv"],
                "as_is": ["outputs/" + REAL, "outputs/meta_pathA_clock2026.csv"],
                "paper_values": "papers/02_ELBOXX/targets.json"},
    "runs": {
        "authors_run_date": {"sys_date": mfake["sys_date"], "nrow_d": int(mfake["nrow_d"]),
                             "year_range": [int(mfake["min_year"]), int(mfake["max_year"])],
                             "how": "faketime '2025-05-06 13:14:00' Rscript scripts/run_pathA.R"},
        "as_is": {"sys_date": mreal["sys_date"], "nrow_d": int(mreal["nrow_d"]),
                  "year_range": [int(mreal["min_year"]), int(mreal["max_year"])],
                  "how": "Rscript scripts/run_pathA.R (real clock)"},
    },
    "targets": out_targets,
    "summary": {
        "n_targets_match_to_rounding_authors_date": sum(t["match_to_rounding_authors_date"] for t in out_targets),
        "n_targets_match_to_rounding_as_is": sum(t["match_to_rounding_as_is"] for t in out_targets),
        "targets_drifting_as_is": [t["id"] for t in out_targets if not t["match_to_rounding_as_is"]],
        "max_abs_rel_diff_as_is_vs_paper": max(abs(t["rel_diff_as_is_vs_paper"]) for t in out_targets),
        "all_within_5pct_as_is": all(t["within_5pct_as_is"] for t in out_targets),
    },
}
with open(os.path.join(OUT, "clock_comparison.json"), "w") as f:
    json.dump(res, f, indent=1)
print(json.dumps(res["summary"], indent=1))
for t in out_targets:
    print(t["id"], t["paper_value"], t["value_authors_run_date_20250506"], t["value_as_is_clock_20261009"],
          "%+.4f" % t["rel_diff_as_is_vs_paper"])

# ---- Deviation note (numbers filled from res, not typed) ----
