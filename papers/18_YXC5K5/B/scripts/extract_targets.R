# Usage: Rscript extract_targets.R <session.RData> <out.csv>
# Loads the saved session of a run of Benchmarking_DataAnalysis.Rmd (purled) and writes every needed number at full precision.
args <- commandArgs(trailingOnly = TRUE)
suppressMessages(library(dplyr))
load(args[1])
rows <- list()
add <- function(name, value) rows[[length(rows) + 1]] <<- data.frame(name = name, value = format(value, digits = 17), stringsAsFactors = FALSE)
for (r in rownames(metrics_matrix)) for (c in colnames(metrics_matrix)) add(paste0("metrics_matrix|", r, "|", c), metrics_matrix[r, c])
for (k in names(undergrads8)) add(paste0("undergrads8|", k), undergrads8[[k]])
for (k in names(undergrads4)) add(paste0("undergrads4|", k), undergrads4[[k]])
add("author_pct1s_8lab_line2067", 100 * mean(get_means(pi10, 10, "author")$mean_prop_1s))
add("author_pct1s_4lab_line2068", 100 * mean(get_means(pi4, 4, "author")$mean_prop_1s))
add("nrow_pi10mat", nrow(pi10mat)); add("nrow_gpt4o10mat_fewx", nrow(gpt4o10mat_fewx)); add("nrow_hum10matx", nrow(hum10matx))
add("hl10_mean|GPT 4o (Few Shot)", mean(hamming_loss_results_10[["GPT 4o (Few Shot)"]]))
add("hl10_mean|Undergraduate Coders", mean(hamming_loss_results_10[["Undergraduate Coders"]]))
add("hl4_mean|Undergraduate Coders", mean(calculate_hamming_loss(pi4mat, hum4matx)))
add("identical_pi_docid_vs_gpt4o10few_docid", identical(as.numeric(pi$docid), as.numeric(gpt_data$gpt4o_10lab_fewshot$docid)))
add("identical_pi_docid_vs_human10_docid", identical(as.numeric(pi$docid), as.numeric(human_data$human_10lab$docid)))
add("setequal_pi_docid_vs_gpt4o10few_docid", setequal(pi$docid, gpt_data$gpt4o_10lab_fewshot$docid))
add("caret_version", as.character(packageVersion("caret")))
write.csv(do.call(rbind, rows), args[2], row.names = FALSE)
cat("wrote", args[2], "\n")
