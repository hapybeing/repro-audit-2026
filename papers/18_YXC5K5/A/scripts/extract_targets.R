# Usage: Rscript extract_targets.R <session.RData> <out.csv>
# Writes every metrics_matrix cell, undergrads8/4, author 1s shares, N and docid-alignment diagnostics (full precision).
args <- commandArgs(TRUE)
suppressMessages({library(tidyverse); library(caret)})
e <- new.env(); load(args[1], envir = e)
rows <- list()
add <- function(obj, key, value) rows[[length(rows) + 1]] <<- data.frame(object = obj, key = key, value = as.character(value))
mm <- e$metrics_matrix
for (r in rownames(mm)) for (cc in colnames(mm)) add("metrics_matrix", paste(r, cc, sep = "|"), format(mm[r, cc], digits = 17))
for (k in names(e$undergrads8)) add("undergrads8", k, format(e$undergrads8[[k]], digits = 17))
for (k in names(e$undergrads4)) add("undergrads4", k, format(e$undergrads4[[k]], digits = 17))
add("author", "pct1s_8lab_share", format(mean(e$get_means(e$pi10, 10, "author")$mean_prop_1s), digits = 17))
add("author", "pct1s_4lab_share", format(mean(e$get_means(e$pi4, 4, "author")$mean_prop_1s), digits = 17))
add("n", "nrow_pi10mat", nrow(e$pi10mat))
add("n", "nrow_gpt4o10mat_fewx", nrow(e$gpt4o10mat_fewx))
add("n", "nrow_hum10matx", nrow(e$hum10matx))
add("diag", "identical_pi_gpt4o10few_docid", identical(e$pi$docid, e$gpt_data$gpt4o_10lab_fewshot$docid))
add("diag", "identical_pi_human10_docid", identical(e$pi$docid, e$human_data$human_10lab$docid))
add("diag", "setequal_pi_gpt4o10few_docid", setequal(e$pi$docid, e$gpt_data$gpt4o_10lab_fewshot$docid))
add("diag", "share_rows_same_docid_pi_vs_gpt4o10few", mean(e$pi$docid == e$gpt_data$gpt4o_10lab_fewshot$docid))
hl10 <- sapply(e$hamming_loss_results_10, mean); hl4 <- sapply(e$hamming_loss_results_4, mean)
for (k in names(hl10)) add("hamming_mean_8lab", k, format(hl10[[k]], digits = 17))
for (k in names(hl4)) add("hamming_mean_4lab", k, format(hl4[[k]], digits = 17))
# secondary context only (not a target): F1 with "1" as positive class for GPT 4o Few Shot 8 labels
f1pos1 <- sapply(1:8, function(i) { a <- factor(e$actual_list_10[[i]], levels = c("0","1")); p <- factor(e$gpt4o10mat_few[[i]], levels = c("0","1"))
  caret::confusionMatrix(p, a, positive = "1")$byClass["F1"] })
add("secondary", "F1_positive1_gpt4o10_few_mean", format(mean(f1pos1, na.rm = TRUE), digits = 17))
out <- do.call(rbind, rows)
write.csv(out, args[2], row.names = FALSE)
cat("wrote", nrow(out), "rows to", args[2], "\n")
