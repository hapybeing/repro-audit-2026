"""Check every link and DOI in final/FINAL_REPORT.md, README.md and final/all25_results.csv (the final release files).
Usage (from the repository root): python3 scripts/check_final_links.py > final/FINAL_link_check.txt
Same method as scripts/check_links.py: DOIs via the DOI handle API (responseCode 1 = registered) plus the resolver status;
URLs via GET after redirects. Relative links are checked as files in the working tree. Exit status 1 if any is broken."""
import json, os, re, sys, datetime, urllib.request, urllib.error, urllib.parse
FILES = ["final/FINAL_REPORT.md", "README.md", "final/all25_results.csv"]
UA = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36"}
URL_RE = re.compile(r"https?://[^\s)\]|>`'\"]+")
DOI_RE = re.compile(r"(?<![\w/.])10\.\d{4,9}/[^\s)\]|,;`'\"]+")
REL_RE = re.compile(r"\]\((?!https?://)([^)#\s]+)\)")


def fetch(u):
    try:
        r = urllib.request.urlopen(urllib.request.Request(u, headers=UA), timeout=60)
        return r.status, r.geturl(), r.read(4000)
    except urllib.error.HTTPError as e:
        return e.code, u, e.read(4000)
    except Exception as e:
        return f"error: {type(e).__name__}", u, b""


urls, dois, rels = {}, {}, {}
for f in FILES:
    t = open(f, encoding="utf-8").read()
    for u in URL_RE.findall(t):
        urls.setdefault(u.rstrip(".,;:"), set()).add(f)
    for d in DOI_RE.findall(URL_RE.sub(" ", t)) + [m.group(1) for m in re.finditer(r"doi\.org/(10\.[^\s)\]|,;`'\"]+)", t)]:
        dois.setdefault(d.rstrip(".,;:"), set()).add(f)
    for r in REL_RE.findall(t):
        rels.setdefault(os.path.normpath(os.path.join(os.path.dirname(f), r)), set()).add(f)
print(f"Final link and DOI check. Generated by scripts/check_final_links.py at {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}.")
print(f"Files: {', '.join(FILES)}. Distinct URLs: {len(urls)}. Distinct DOIs: {len(dois)}. Relative links: {len(rels)}.\n")
bad = 0
print("== DOIs")
for d in sorted(dois):
    _, _, body = fetch("https://doi.org/api/handles/" + urllib.parse.quote(d, safe="/"))
    try:
        rc = json.loads(body).get("responseCode")
    except Exception:
        rc = None
    bad += rc != 1
    print(f"[{'OK' if rc == 1 else 'BROKEN'}] {d} | handle API responseCode {rc} | in {', '.join(sorted(dois[d]))}")
print("\n== URLs")
for u in sorted(urls):
    if u.startswith("https://doi.org/"):
        print(f"[see DOI] {u}"); continue
    st, final, body = fetch(u)
    good = isinstance(st, int) and 200 <= st < 400
    cf = st == 403 and b"Just a moment" in body
    bad += not (good or cf)
    print(f"[{'OK' if good else ('OK (Cloudflare bot check)' if cf else 'BROKEN')}] {u} | HTTP {st} | in {', '.join(sorted(urls[u]))}")
print("\n== Relative links (files in the working tree)")
for r in sorted(rels):
    e = os.path.exists(r)
    bad += not e
    print(f"[{'OK' if e else 'BROKEN'}] {r} | in {', '.join(sorted(rels[r]))}")
print(f"\nRESULT: {'PASS' if bad == 0 else 'FAIL'} ({bad} broken)")
sys.exit(1 if bad else 0)
