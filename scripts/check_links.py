"""Check that every link and DOI in README.md and the batch K report and target table resolves.
Usage (from repo/): python3 scripts/check_links.py 1 > batches/batch1_link_check.txt
For each DOI: the DOI handle API (https://doi.org/api/handles/<doi>, responseCode 1 = registered) and the HTTP status
after following redirects from https://doi.org/<doi>. For each URL: HTTP status after redirects (GET, 60 s timeout).
Publisher sites that answer scripts with a Cloudflare 403 are reported as such; the DOI handle check is what shows the DOI exists."""
import json, re, sys, datetime, urllib.request, urllib.error, urllib.parse

K = sys.argv[1]
FILES = ["README.md", f"batches/batch{K}_report.md", f"batches/batch{K}_targets.md"]
UA = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36"}
URL_RE = re.compile(r"https?://[^\s)\]|>`'\"]+")
DOI_RE = re.compile(r"(?<![\w/.])10\.\d{4,9}/[^\s)\]|,;`'\"]+")


def fetch(u):
    try:
        r = urllib.request.urlopen(urllib.request.Request(u, headers=UA), timeout=60)
        body = r.read(4000)
        return r.status, r.geturl(), body
    except urllib.error.HTTPError as e:
        return e.code, e.geturl() if hasattr(e, "geturl") else u, e.read(4000)
    except Exception as e:
        return f"error: {type(e).__name__}", u, b""


def note(st, body):
    b = body.decode("utf-8", "replace")
    if st == 403 and ("Just a moment" in b or "cloudflare" in b.lower()):
        return "Cloudflare bot check (site blocks scripts; resolves in a browser)"
    return ""


urls, dois = {}, {}
for f in FILES:
    txt = open(f, encoding="utf-8").read()
    for u in URL_RE.findall(txt):
        u = u.rstrip(".,;:")
        urls.setdefault(u, set()).add(f)
    for d in DOI_RE.findall(URL_RE.sub(" ", txt)) + [m.group(1) for m in re.finditer(r"doi\.org/(10\.[^\s)\]|,;`'\"]+)", txt)]:
        dois.setdefault(d.rstrip(".,;:"), set()).add(f)

print(f"Link and DOI check for batch {K}. Generated by scripts/check_links.py {K} at "
      f"{datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}.")
print(f"Files: {', '.join(FILES)}. Distinct URLs: {len(urls)}. Distinct DOIs: {len(dois)}.\n")
bad = 0
print("== DOIs")
for d in sorted(dois):
    st_h, _, body = fetch("https://doi.org/api/handles/" + urllib.parse.quote(d, safe="/"))
    try:
        rc = json.loads(body).get("responseCode")
    except Exception:
        rc = None
    st, final, b2 = fetch("https://doi.org/" + d)
    ok = rc == 1
    bad += 0 if ok else 1
    print(f"[{'OK' if ok else 'BROKEN'}] {d} | handle API responseCode {rc} (HTTP {st_h}) | resolver HTTP {st} -> {final} {note(st, b2)} | in {', '.join(sorted(dois[d]))}")
print("\n== URLs")
for u in sorted(urls):
    if u.startswith("https://doi.org/"):
        print(f"[see DOI] {u}")
        continue
    st, final, body = fetch(u)
    ok = st == 200 or (st == 403 and note(st, body))
    bad += 0 if ok else 1
    print(f"[{'OK' if st == 200 else ('BLOCKED-BY-SITE' if ok else 'BROKEN')}] {u} | HTTP {st} -> {final} {note(st, body)} | in {', '.join(sorted(urls[u]))}")
print(f"\nRESULT: {'PASS' if bad == 0 else 'FAIL'} ({bad} broken)")
sys.exit(1 if bad else 0)
