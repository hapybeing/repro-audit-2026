"""Write the per-paper table of batches/batch{K}_report.md from batches/batch{K}_results_rule4.csv and papers/<id>/META.md.
Usage (from repo/): python3 scripts/make_report_rule4_table.py 1
The table sits between the markers <!-- table:rule4:start --> and <!-- table:rule4:end --> and is replaced in place."""
import csv, re, sys

K = sys.argv[1]
rows = list(csv.DictReader(open(f"batches/batch{K}_results_rule4.csv")))
L = ["<!-- table:rule4:start -->",
     f"Generated by `scripts/make_report_rule4_table.py {K}` from `batches/batch{K}_results_rule4.csv` and `papers/<id>/META.md`.", "",
     "| Paper | Title (journal, year) | Paper DOI | Dataset DOI | Agents A / B | Class (rule 4) | Alternative |" + (" Sources |" if K != "1" else ""),
     "|---|---|---|---|---|---|---|" + ("---|" if K != "1" else "")]
for r in rows:
    meta = open(f"papers/{r['paper_id']}/META.md", encoding="utf-8").read()
    title = re.search(r"- Paper: (.+)", meta).group(1).strip()
    journal = re.sub(r" \((\d{4})\)$", r", \1", re.search(r"- Journal: (.+)", meta).group(1).strip())
    pd = r["paper_doi"].replace("https://doi.org/", "")
    dd = r["dataset_doi"].replace("https://doi.org/", "")
    L.append(f"| {r['paper_id']} | {title} ({journal}) | [{pd}]({r['paper_doi']}) | [{dd}]({r['dataset_doi']}) | "
             f"{r['class_agents_A']} / {r['class_agents_B']} | {r['class_rule4']} | {r['alternative']} |"
             + (f" papers/{r['paper_id']}/META.md; targets.json; A/results.json |" if K != "1" else ""))
L.append("<!-- table:rule4:end -->")
p = f"batches/batch{K}_report.md"
s = open(p, encoding="utf-8").read()
s = re.sub(r"<!-- table:rule4:start -->.*?<!-- table:rule4:end -->", "\n".join(L), s, flags=re.S)
open(p, "w", encoding="utf-8").write(s)
print("\n".join(L))
