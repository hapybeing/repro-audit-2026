cache = {}


def filenums(p):
    if p not in cache:
        try:
            t = open(p, encoding="utf-8", errors="replace").read()
        except (FileNotFoundError, IsADirectoryError):
            t = ""
        t = re.sub(r"(?<=\d),(?=\d{3}\b)", "", t)
        cache[p] = {float(x) for x in re.findall(r"-?\d+(?:\.\d+)?", t)} | {abs(float(x)) for x in re.findall(r"-?\d+(?:\.\d+)?", t)}
    return cache[p]


