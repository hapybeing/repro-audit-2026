"""Check every number in final/FINAL_REPORT.md, final/all25_results.csv and final/all25_counts.json.
Usage (from the repository root): python3 scripts/check_final_numbers.py > final/FINAL_number_check.txt

Three layers, written separately from scripts/make_final.py so the two do not share code:
 1. Recompute every cell of final/all25_results.csv from the batch files and compare.
 2. Recompute every count in final/all25_counts.json from the batch files, and cross-check against the counts each
    published batch file states (batch{k}_counts_rule4.json, batch{k}_code_observations_counts.json, and the
    "N of M computable targets" sentence of each batch report).
 3. Report: count lines and table rows are compared with the JSON and CSV; every other number token is looked up in
    the files cited on its line, in its section heading, or in the section's stated sources. Identifiers (DOIs, URLs,
    paths, dates, paper ids, target ids, observation ids, CHANGELOG refs, commit hashes) are not measurements.
Also fails on an em dash, on any percent sign other than the 5% tolerance quoted from PROTOCOL.md, and on a
README Status line that is not the final one. Exit status 1 on any failure."""
import csv, json, re, subprocess, sys
from collections import Counter

out, fails = [], 0
CLS = "ABCDE"


def ok(cond, msg):
    global fails
    out.append(f"  [{'OK' if cond else 'FAIL'}] {msg}")
    if not cond:
        fails += 1


def table(p):
    with open(p, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def classcount(seq):
    c = Counter(seq)
    return {k: c.get(k, 0) for k in CLS}


res = table("final/all25_results.csv")
cj = json.load(open("final/all25_counts.json", encoding="utf-8"))
selected = {r["paper_doi"].lower(): r for r in table("selection/selected.csv") if r["eligible"] == "True"}

# ------------------------------------------------------------------ layer 1
out.append("Final number check. Generated by scripts/check_final_numbers.py.")
out.append("")
out.append("== Layer 1: final/all25_results.csv recomputed from batch files")
by_id = {r["id"]: r for r in res}
ok(len(res) == 25 and [r["id"][:2] for r in res] == [f"{i:02d}" for i in range(1, 26)], "25 rows, ids 01 to 25 in order")
exp_paper = {}
for k in range(1, 6):
    rules = json.load(open(f"batches/batch{k}_class_rules.json", encoding="utf-8"))
    agents = {r["paper_id"]: (r["class_A"], r["class_B"]) for r in table(f"batches/batch{k}_results.csv")}
    tg = table(f"batches/batch{k}_targets.csv")
    obs = table(f"batches/batch{k}_code_observations.csv")
    rep = open(f"batches/batch{k}_report.md", encoding="utf-8").read()
    for r in table(f"batches/batch{k}_results_rule4.csv"):
        pid = r["paper_id"]
        s = selected[r["paper_doi"].replace("https://doi.org/", "").lower()]
        T = [t for t in tg if t["paper"] == pid and t["row_type"] == "paper target" and t["target_id"] != "(none)"]
        matched = len([t for t in T if "match paper" in t["match_status"]])
        computed = len([t for t in T if not t["match_status"].startswith("not computed")])
        ab = True
        for t in T:
            if t["match_status"].startswith("not computed"):
                continue
            if t.get("AB_agree") is not None:
                ab = ab and t["AB_agree"].startswith("yes")
            else:  # batches 1 and 2: compare the two values at the paper's decimals
                d = int(t["decimals"] or 0)
                ab = ab and (t["A_value"] == t["B_value"] or abs(float(t["A_value"]) - float(t["B_value"])) < 0.5 * 10 ** (-d))
        alt = rules[pid]["alt_class"]
        e = {"batch": str(k), "title": s["paper_title"], "journal": s["journal"], "year": s["pub_year"],
             "language": s["code_language"], "main_class": r["class_rule4"],
             "alternative_class": "excluded (no computational target)" if alt == "no computational target" else alt,
             "alternative_reason": rules[pid]["alt_label"], "targets_matched_both_agents": str(matched),
             "targets_total": str(len(T)), "targets_computed": str(computed),
             "agent_class_A": agents[pid][0], "agent_class_B": agents[pid][1],
             "ab_agree_class": "yes" if agents[pid][0] == agents[pid][1] else "no",
             "ab_agree_every_computed_target": "yes" if ab else "no",
             "verified_code_observations": str(len([o for o in obs if o["paper"] == pid and o["status"] == "verified finding"]))}
        if k == 1:
            ok("self-attested local freeze 2026-10-09 15:39:18 UTC" in by_id[pid]["prereg_freeze"]
               and "2026-10-09 15:39:18 UTC" in open("batches/batch1_prereg_hashes.txt").read(), f"{pid} freeze reference (batch 1 self-attested)")
        else:
            m = re.search(r"issue #(\d+), commit ([0-9a-f]{7})", by_id[pid]["prereg_freeze"])
            okc = bool(m) and f"issues/{m.group(1)}" in rep and f"commit {m.group(2)}" in rep and m.group(1) == str(k - 1)
            git = subprocess.run(["git", "cat-file", "-t", m.group(2)], capture_output=True, text=True).stdout.strip() if m else ""
            ok(okc and git == "commit", f"{pid} freeze reference {m.group(0) if m else '?'} in batches/batch{k}_report.md and in git history")
        exp_paper[pid] = e
        bad = [f for f in e if by_id[pid][f] != e[f]]
        ok(not bad, f"{pid}: {len(e)} cells match" + (f"; differing: {bad}" if bad else ""))

