"""Re-check every sha256 in batches/batch{K}_prereg_hashes.txt against the files as they are now.
Usage (from repo/): python3 scripts/check_prereg_hashes.py 3 > batches/batch3_prereg_hash_check.txt
Exit status 1 if any file is missing or its hash differs."""
import hashlib, os, re, sys, datetime
K = sys.argv[1]
src = f"batches/batch{K}_prereg_hashes.txt"
rows = [l.split(None, 1) for l in open(src) if re.match(r"^[0-9a-f]{64}\s", l)]
ok = bad = 0
out = []
for h, p in rows:
    p = p.strip()
    if not os.path.exists(p):
        out.append(f"MISSING {p}"); bad += 1; continue
    got = hashlib.sha256(open(p, "rb").read()).hexdigest()
    if got == h:
        out.append(f"OK {p}"); ok += 1
    else:
        out.append(f"CHANGED {p} (frozen {h}, now {got})"); bad += 1
now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
print(f"Pre-registration hash check for batch {K}. Generated by scripts/check_prereg_hashes.py {K} at {now}, against {src}.")
print(f"Files listed: {len(rows)}. Matching: {ok}. Missing or changed: {bad}.")
print("\n".join(out))
print(f"RESULT: {'PASS' if bad == 0 else 'FAIL'}")
sys.exit(1 if bad else 0)
