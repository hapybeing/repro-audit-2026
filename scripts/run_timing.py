"""Record when the batch K agent runs started relative to the pre-registration freeze.
Usage (from repo/): python3 scripts/run_timing.py 4 > batches/batch4_run_timing.txt
Reads: the freeze line of batches/batch{K}_prereg_hashes.txt; the modification time of batches/batch{K}_run_brief.md;
the modification times of every file the agents wrote under papers/<id>/{A,B}/ (earliest five listed; LOG.md files are
skipped because the status note added after the runs changes their modification time); and the first time stamp
written in each agent LOG.md (agents' own clock reading, IST or UTC as each log states).
File modification times are those of the working copy at the time this script runs; a git checkout does not keep them."""
import datetime, glob, os, re, sys

K = int(sys.argv[1])
PIDS = {4: ["16_QZNVZ0", "17_T1NXVQ", "18_YXC5K5", "19_KH0SQ2", "20_SINIYU"],
        5: ["21_LEFTNE", "22_W2TSVL", "23_FXRNBA", "24_U9CKK6", "25_914AN0"]}[K]


def utc(ts):
    return datetime.datetime.fromtimestamp(ts, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")


freeze = next(l.strip() for l in open(f"batches/batch{K}_prereg_hashes.txt") if l.startswith("frozen"))
print(f"Run timing for batch {K}. Generated by scripts/run_timing.py {K} at {utc(datetime.datetime.now().timestamp())}.")
print(f"Pre-registration: {freeze} (batches/batch{K}_prereg_hashes.txt)")
print(f"Run brief batches/batch{K}_run_brief.md last modified: {utc(os.path.getmtime(f'batches/batch{K}_run_brief.md'))}")
files = []
for p in PIDS:
    for f in glob.glob(f"papers/{p}/[AB]/**/*", recursive=True):
        if os.path.isfile(f) and not f.endswith("LOG.md"):
            files.append((os.path.getmtime(f), f))
files.sort()
print(f"Earliest modification times of agent files (of {len(files)} files, LOG.md skipped):")
for t, f in files[:5]:
    print(f"  {utc(t)}  {f}")
print("First time stamp written in each agent LOG.md (agent's own reading; zone as the log states):")
for p in PIDS:
    for ag in "AB":
        txt = open(f"papers/{p}/{ag}/LOG.md", encoding="utf-8").read()
        txt = re.sub(r"<!-- status-note:start -->.*?<!-- status-note:end -->", "", txt, flags=re.S)
        zone = "UTC" if re.search(r"All times UTC", txt) else "IST"
        m = re.search(r"\b([0-2]\d:[0-5]\d)\b", re.sub(r"UTC\+05:30|UTC \+ 5:30|IST = UTC \+ ?5:30", "", txt))
        print(f"  {p} {ag}: {m.group(1) if m else 'none'} {zone}")
